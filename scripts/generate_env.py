"""Create a .env file with strong random secrets.

    python scripts/generate_env.py --domain study.example.org --contact you@example.org [--speech] [--force]

Secrets are generated with the `secrets` module (CSPRNG). The file is created
with 0600 permissions and is git-ignored. Never commit it.
"""

from __future__ import annotations

import argparse
import os
import secrets
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]


def _secret() -> str:
    return secrets.token_urlsafe(48)


def render(domain: str, contact: str, speech: bool) -> str:
    lines = [
        "# Generated by scripts/generate_env.py - keep private, never commit.",
        f"DOMAIN={domain}",
        f"CONTACT_EMAIL={contact}",
        f"POSTGRES_SUPERUSER_PASSWORD={_secret()}",
        "APP_DB_USER=voice_study",
        f"APP_DB_PASSWORD={_secret()}",
        "APP_DB_NAME=voice_study",
        "# Bearer token for the researcher API (create participant links, export data).",
        f"RESEARCHER_TOKEN={_secret()}",
    ]
    if speech:
        lines += [
            "# Voice answers via Google Speech-to-Text (see docker-compose.speech.yml).",
            "COMPOSE_FILE=docker-compose.yml:docker-compose.speech.yml",
            "ASR_LANGUAGE=en-GB",
        ]
    return "\n".join(lines) + "\n"


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("--domain", default="localhost")
    parser.add_argument("--contact", required=True, help="researcher e-mail shown on the consent page")
    parser.add_argument("--speech", action="store_true", help="enable voice answers (Google Speech-to-Text)")
    parser.add_argument("--output", type=Path, default=ROOT / ".env")
    parser.add_argument("--force", action="store_true", help="overwrite an existing file")
    args = parser.parse_args()

    if "\n" in args.domain or "\n" in args.contact:
        print("values must be single-line", file=sys.stderr)
        return 1
    if args.output.exists() and not args.force:
        print(f"{args.output} already exists; use --force to replace it", file=sys.stderr)
        return 1
    fd = os.open(args.output, os.O_WRONLY | os.O_CREAT | os.O_TRUNC, 0o600)
    with os.fdopen(fd, "w") as handle:
        handle.write(render(args.domain, args.contact, args.speech))
    print(f"wrote {args.output}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
